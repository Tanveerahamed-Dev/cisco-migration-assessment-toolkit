"""AssessHub sample-fleet freshness gate (Plan A / Tier-2 #10).

The class this pins: the bundled demo snapshot froze at 56 of 86 snapshot keys — every
axis shipped after mid-June was simply invisible in the product's first-run experience.
The sample is regenerated by webapp/sample_data/build_sample.py (which drives the REAL
pipeline), and this gate enforces: sample keys ⊇ golden keys. The golden file already
excludes the date-relative sections and never contains opt-in engines, so plain
superset is the exact contract — a new golden-frozen axis that doesn't reach the demo
fails here until the sample is regenerated."""
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent


def test_sample_fleet_carries_every_golden_section():
    sample = json.loads((ROOT / "webapp" / "sample_data" / "sample_fleet.snapshot.json"
                         ).read_text(encoding="utf-8"))
    golden = json.loads((ROOT / "tests" / "golden" / "snapshot.json"
                         ).read_text(encoding="utf-8"))
    missing = sorted(set(golden) - set(sample))
    assert not missing, (
        f"the bundled demo snapshot is STALE — regenerate it "
        f"(python webapp/sample_data/build_sample.py); missing section(s): {missing}")
    # sanity: it is a real multi-device demo, not a stub
    assert len(sample.get("devices") or {}) >= 10
